import type { Difficulty, Exercise, ExerciseCategory } from '../types'

/**
 * Original exercise library written for this demo.
 * Descriptions are general coaching cues, not individual medical advice.
 * Steps are separated with "|" to keep the file compact.
 */

const slug = (s: string) =>
  'ex-' + s.toLowerCase().replace(/[^a-z0-9]+/g, '-').replace(/(^-|-$)/g, '')

const B: Difficulty = 'Beginner'
const I: Difficulty = 'Intermediate'
const A: Difficulty = 'Advanced'

function x(
  name: string,
  category: ExerciseCategory,
  primaryMuscle: string,
  secondary: string,
  equipment: string,
  difficulty: Difficulty,
  description: string,
  steps: string,
  safety?: string,
): Exercise {
  return {
    id: slug(name),
    name,
    category,
    primaryMuscle,
    secondaryMuscles: secondary ? secondary.split(',').map((s) => s.trim()) : [],
    equipment,
    difficulty,
    description,
    instructions: steps.split('|').map((s) => s.trim()),
    safety,
  }
}

